from pycrazyswarm import Crazyswarm
import numpy as np

Z_HEIGHT = 0.6  # Target altitude

def land_all(swarm):
    for cf in swarm.allcfs.crazyflies:
        print(cf.position())
        cf.goTo(np.append(cf.position()[:2], -0.75), 0.0, 1.5)
    swarm.timeHelper.sleep(1.5)

def move_to_positions(swarm, pos_xy, speed=0.5):
    num_drones = len(swarm.allcfs.crazyflies)
    durations = []
    for i in range(num_drones):
        current_pos = swarm.allcfs.crazyflies[i].position()[:2]
        target_pos = pos_xy[:, i]
        dist = np.linalg.norm(current_pos - target_pos)
        durations.append(dist / speed)
    duration = max(max(durations),2)
    for i in range(num_drones):
        target = pos_xy[:, i].tolist() + [Z_HEIGHT]
        swarm.allcfs.crazyflies[i].goTo(target, 0.0, duration)

    swarm.timeHelper.sleep(duration)

